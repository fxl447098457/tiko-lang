#!/usr/bin/env python3
"""windowszones.py -- CLDR's windowsZones.xml into pkg/std/tz/tzwinmap.tiko.

    python3 windowszones.py <windowsZones.xml> <cldr-release> [out.tiko]

Takes each Windows time zone key's territory "001" mapping -- CLDR's choice of the
one IANA zone that stands for that Windows zone -- and writes them as a tiko lookup.
Fetch the input from the CLDR release named:
    https://raw.githubusercontent.com/unicode-org/cldr/<release>/common/supplemental/windowsZones.xml
CLDR data is under the Unicode License v3 (licences/LICENSE.unicode).
"""
import os
import re
import sys
import xml.etree.ElementTree as ET


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    src, release = sys.argv[1], sys.argv[2]
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[3] if len(sys.argv) == 4 else os.path.join(here, '..', '..', 'pkg', 'std', 'tz', 'tzwinmap.tiko')
    pairs = []
    for mz in ET.parse(src).getroot().iter('mapZone'):
        if mz.get('territory') == '001':
            key, iana = mz.get('other'), mz.get('type')
            if not re.fullmatch(r'[A-Za-z0-9 ().+\-]+', key) or not re.fullmatch(r'[A-Za-z0-9_/+\-]+', iana):
                sys.exit('windowszones.py: unexpected text %r -> %r' % (key, iana))
            pairs.append((key, iana))
    if len(pairs) < 100:
        sys.exit('windowszones.py: only %d mappings -- wrong file?' % len(pairs))
    pairs.sort(key=lambda p: p[0].lower())
    lines = [
        '#module "tz"',
        "'' std/tz: Windows time zone keys to IANA ids -- GENERATED by tools/tzdb/windowszones.py",
        "'' from CLDR %s common/supplemental/windowsZones.xml, territory \"001\". Do not edit:" % release,
        "'' regenerate it. CLDR data: Copyright (c) Unicode, Inc., Unicode License v3",
        "'' (licences/LICENSE.unicode).",
        '',
        "'' The IANA id CLDR gives for Windows key KEY (GetDynamicTimeZoneInformation's",
        "'' TimeZoneKeyName, matched without regard to case), or \"\".",
        'function tzWindowsToIana( byref key as const ustring ) as ustring',
        '    select case lcase( key )',
    ]
    for key, iana in pairs:
        lines.append('    case "%s" : return "%s"' % (key.lower(), iana))
    lines += ['    end select', '    return ""', 'end function', '']
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines))
    print('windowszones.py: %d keys -> %s' % (len(pairs), out))


if __name__ == '__main__':
    main()
