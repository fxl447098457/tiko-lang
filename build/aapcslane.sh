#!/bin/sh
# aapcslane.sh -- the RUNNING AAPCS64 ABI lane: tiko-compiled code against a clang-built C
# library, called and calling back, on both AAPCS64s.
#
#   build/aapcslane.sh              the Mac (macos-arm64), the Linux VM on it (linux-arm64),
#                                   then the linux-x86_64 control in WSL
#   build/aapcslane.sh --mac-only   the Mac alone
#   build/aapcslane.sh --vm-only    the linux-arm64 VM alone
#
# THE VM (docs/tiko-linux-arm64, docs/build.md "Linux arm64 VM on the Mac"): Lima instance
# TIKO_LIMA_VM (default 'tk') on the Mac, aarch64 Ubuntu with clang-23. It sees the Mac's ~/tkm
# at /Users/<user>/tkm, which is where the lane's files are copied; its own home is not the
# Mac's. Generic AAPCS64 differs from Apple's in exactly what this lane exercises hardest:
# narrow arguments are not extended by the caller, and varargs travel in registers and are read
# back through a 32-byte va_list record (cva_arg is tiko's own sequence there).
#
# tests/abi/apple/lane.c and lane.tiko (GENERATED by build/aapcslane.py from one table):
# every shape -- integer aggregates of 1 to 33 bytes, HFAs of 1 to 5 floats and doubles
# (nested, arrayed, a union), mixed and non-HFA unions, over-16-byte ones by address -- passed
# and returned by value in both directions, through procedure pointers both ways,
# register-exhausting prefixes, and varargs both ways. C owns main and makes every check, so
# the tiko side needs no runtime: it links nothing of tiko-rt.
#
# WHY: build/aapcsig.sh proves tiko's IR SIGNATURES equal clang's, which decides the
# registers -- but only a real caller and callee prove the bytes arrive (docs/tiko-macos M3).
# The linux-x86_64 run of the same lane is the control: it passes, so a Mac failure is the
# Apple ABI, not the lane.
#
# Needs: bin/tiko built; ssh to the Mac (TIKO_MAC_HOST, default 'mac'; extra ssh options in
# TIKO_MAC_SSH_OPTS) with the Command Line Tools and Homebrew LLVM there, and Lima with the
# VM; WSL with clang (or clang-18, Ubuntu's versioned name) for the control. Exits 1 on any
# failure.

ROOT=$(cd "$(dirname "$0")/.." && pwd)
case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*) EXT=".exe" ;;
    *) echo "aapcslane: run from Windows (it drives ssh and WSL)" >&2; exit 3 ;;
esac
TKO="$ROOT/bin/tiko$EXT"
[ -x "$TKO" ] || { echo "aapcslane: build tiko first (build/build.sh)" >&2; exit 3; }
HOST=${TIKO_MAC_HOST:-mac}
SSHO=${TIKO_MAC_SSH_OPTS:-}
VM=${TIKO_LIMA_VM:-tk}
RUN_MAC=1; RUN_VM=1; RUN_CTL=1
case "${1:-}" in
    --mac-only) RUN_VM=0; RUN_CTL=0 ;;
    --vm-only)  RUN_MAC=0; RUN_CTL=0 ;;
    "") ;;
    *) echo "aapcslane: unknown option '$1'" >&2; exit 3 ;;
esac
PY=${PYTHON:-python}
command -v "$PY" > /dev/null 2>&1 || PY=python3

"$PY" -I "$ROOT/build/aapcslane.py" --check || exit 2

W="$ROOT/build/.aapcslane"
mkdir -p "$W"
fail=0

# Copies the lane's files to the Mac's ~/tkm/aapcslane (the VM sees the same directory).
to_mac( ) {
    # shellcheck disable=SC2086
    ssh -o BatchMode=yes $SSHO "$HOST" 'mkdir -p ~/tkm/aapcslane' < /dev/null || { echo "FAIL: no ssh to $HOST"; exit 3; }
    # shellcheck disable=SC2086
    scp -q -o BatchMode=yes $SSHO "$@" "$HOST:tkm/aapcslane/" || { echo "FAIL: scp to $HOST"; exit 3; }
}
cp "$ROOT/tests/abi/apple/lane.c" "$W/lane.c"

# ------------------------------------------------------------------ the Mac
if [ "$RUN_MAC" = "1" ]; then
    "$TKO" -c -target macos-arm64 "$ROOT/tests/abi/apple/lane.tiko" -o "$W/lane-mac.o" > "$W/tiko-mac.log" 2>&1 \
        || { echo "FAIL mac: tiko did not compile lane.tiko"; head -5 "$W/tiko-mac.log"; exit 1; }
    # THE REMOTE STEP IS A FILE, run by a login zsh: a non-login ssh shell has no Homebrew on
    # PATH, and variables in an inline ssh command expand on the wrong side.
    cat > "$W/mac.sh" <<'EOF'
set -u
cd ~/tkm/aapcslane || exit 2
CC=/opt/homebrew/opt/llvm/bin/clang
[ -x $CC ] || CC=/usr/bin/clang
SDK=$(xcrun --show-sdk-path)
$CC -target arm64-apple-macosx13.0 -isysroot $SDK -O1 -c lane.c -o lane-c.o || { print "rc=2 clang lane.c"; exit 2; }
$CC -target arm64-apple-macosx13.0 -isysroot $SDK lane-c.o lane-mac.o -o lane || { print "rc=2 link"; exit 2; }
./lane
print "rc=$?"
EOF
    sed -i 's/\r$//' "$W/mac.sh"
    to_mac "$W/lane.c" "$W/lane-mac.o" "$W/mac.sh"
    # shellcheck disable=SC2086
    ssh -o BatchMode=yes $SSHO "$HOST" zsh -l tkm/aapcslane/mac.sh < /dev/null > "$W/mac.out" 2>&1
    sed 's/^/macos-arm64: /' "$W/mac.out"
    grep -q '^rc=0$' "$W/mac.out" || { echo "FAIL macos-arm64 lane"; fail=1; }
fi

# ------------------------------------------------------------------ the VM
if [ "$RUN_VM" = "1" ]; then
    "$TKO" -c -target linux-arm64 "$ROOT/tests/abi/apple/lane.tiko" -o "$W/lane-a64.o" > "$W/tiko-a64.log" 2>&1 \
        || { echo "FAIL linux-arm64: tiko did not compile lane.tiko"; head -5 "$W/tiko-a64.log"; exit 1; }
    # vm.sh runs INSIDE the VM, in the Mac's ~/tkm/aapcslane, which it is handed: the VM's own
    # home is not the Mac's. vmrun.sh runs on the Mac (login zsh: limactl is Homebrew's).
    cat > "$W/vm.sh" <<'EOF'
set -u
cd "$1" || { echo "rc=2 no $1"; exit 2; }
CC=clang-23
command -v $CC > /dev/null 2>&1 || CC=clang
$CC -O1 -c lane.c -o lane-c-a64.o || { echo "rc=2 clang lane.c"; exit 2; }
$CC lane-c-a64.o lane-a64.o -o lane-a64 || { echo "rc=2 link"; exit 2; }
./lane-a64
echo "rc=$?"
EOF
    cat > "$W/vmrun.sh" <<'EOF'
limactl shell "$1" -- bash "$HOME/tkm/aapcslane/vm.sh" "$HOME/tkm/aapcslane"
EOF
    sed -i 's/\r$//' "$W/vm.sh" "$W/vmrun.sh"
    to_mac "$W/lane.c" "$W/lane-a64.o" "$W/vm.sh" "$W/vmrun.sh"
    # shellcheck disable=SC2086
    ssh -o BatchMode=yes $SSHO "$HOST" zsh -l tkm/aapcslane/vmrun.sh "$VM" < /dev/null > "$W/vm.out" 2>&1
    sed 's/^/linux-arm64: /' "$W/vm.out"
    grep -q '^rc=0$' "$W/vm.out" || { echo "FAIL linux-arm64 lane"; fail=1; }
fi

# ------------------------------------------------------------------ the control
if [ "$RUN_CTL" = "1" ]; then
    "$TKO" -c -target linux-x86_64 "$ROOT/tests/abi/apple/lane.tiko" -o "$W/lane-linux.o" > "$W/tiko-linux.log" 2>&1 \
        || { echo "FAIL linux: tiko did not compile lane.tiko"; head -5 "$W/tiko-linux.log"; exit 1; }
    mnt( ) { echo "$1" | sed 's#^/\([a-zA-Z]\)/#/mnt/\L\1/#'; }
    cat > "$W/linux.sh" <<EOF
set -u
D=\$HOME/aapcslane; mkdir -p \$D; cd \$D
cp "$(mnt "$W")/lane.c" "$(mnt "$W")/lane-linux.o" .
CC=clang
command -v \$CC > /dev/null 2>&1 || CC=clang-18
\$CC -O1 -c lane.c -o lane-c.o || { echo "rc=2 clang"; exit 2; }
\$CC lane-c.o lane-linux.o -o lane || { echo "rc=2 link"; exit 2; }
./lane
echo "rc=\$?"
EOF
    sed -i 's/\r$//' "$W/linux.sh"
    MSYS_NO_PATHCONV=1 wsl.exe -- bash "$(mnt "$W")/linux.sh" < /dev/null > "$W/linux.out" 2>&1
    sed 's/^/linux-x86_64 control: /' "$W/linux.out"
    grep -q '^rc=0$' "$W/linux.out" || { echo "FAIL linux-x86_64 control"; fail=1; }
fi

[ "$fail" = "0" ] && echo "aapcslane: ok"
exit $fail
