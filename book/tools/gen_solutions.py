#!/usr/bin/env python3
"""Generate the Appendix G page, the solutions index, from the chapters and their solutions.

An exercise that has a worked solution ends with a `{solution="exNN-MM"}` marker, and the
solution is `examples/chNN/solutions/exNN-MM.tiko` (or `.bas`), which the listing harness
compiles and runs like any other listing (B19). The appendix is that set, rendered: one line
per solved exercise. A marker without its file, or a file without its marker, stops the
build, so the index cannot point at nothing.

    python tools/gen_solutions.py
"""
from __future__ import annotations

import datetime
import pathlib
import re
import sys

CHAPTER_RE = re.compile(r"^ch(\d\d)-.*\.md$")
MARKER_RE = re.compile(r'\{solution="(ex(\d\d)-(\d\d))"\}')
ITEM_RE = re.compile(r"^(\d+)\.\s+(.*)$")


def first_sentence(text: str) -> str:
    """The task, cut at its first sentence -- the index is a pointer, not a restatement."""
    text = MARKER_RE.sub("", text).strip()
    text = re.sub(r"\s+", " ", text)
    # A period inside backticks (a file name, `0.1`) does not end a sentence.
    depth = False
    for i, ch in enumerate(text):
        if ch == "`":
            depth = not depth
        elif not depth and ch in ".?!" and (i + 1 == len(text) or text[i + 1] == " "):
            return text[: i + 1]
    return text


def exercises(md: str):
    """(number, text) for each numbered item under '## Exercises', continuation lines joined."""
    part = md.split("\n## Exercises", 1)
    if len(part) < 2:
        return []
    body = part[1].split("\n## ", 1)[0]
    items: list[list] = []
    for line in body.splitlines():
        m = ITEM_RE.match(line)
        if m:
            items.append([int(m.group(1)), m.group(2)])
        elif items and line.startswith("   "):
            items[-1][1] += " " + line.strip()
    return items


def main() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    out = root / "src" / "appendix-G-solutions.md"

    rows = []
    total = 0
    seen: set[str] = set()
    for md_path in sorted((root / "src").glob("ch*.md")):
        m = CHAPTER_RE.match(md_path.name)
        if not m:
            continue
        chap = int(m.group(1))
        md = md_path.read_text(encoding="utf-8")
        title = re.sub(r"\s*\{#[^}]*\}", "", md.splitlines()[0].lstrip("# ")).strip()
        for num, text in exercises(md):
            total += 1
            mk = MARKER_RE.search(text)
            if not mk:
                continue
            name, nn, _ = mk.groups()
            if int(nn) != chap:
                sys.exit(f"gen_solutions: {md_path.name} exercise {num} names {name}, another chapter's")
            sol_dir = root / "examples" / f"ch{nn}" / "solutions"
            found = [p for p in (sol_dir / f"{name}.tiko", sol_dir / f"{name}.bas") if p.exists()]
            if not found:
                sys.exit(f"gen_solutions: {md_path.name} exercise {num}: no {name}.tiko or .bas in {sol_dir}")
            sol = found[0]
            seen.add(str(sol.resolve()))
            note = ""
            meta = sol.with_suffix(".meta")
            if meta.exists():
                b = re.search(r"^blocked:\s*(T\d+)", meta.read_text(encoding="utf-8"), re.M)
                if b:
                    note = f" (blocked: {b.group(1)})"
            rel = sol.relative_to(root / "examples").as_posix()
            rows.append((chap, num, title, first_sentence(text), rel, note))

    # Every solution file belongs to an exercise.
    for p in sorted((root / "examples").glob("ch*/solutions/ex*.*")):
        if p.suffix in (".tiko", ".bas") and str(p.resolve()) not in seen:
            sys.exit(f"gen_solutions: {p.relative_to(root)} has no {{solution=...}} marker in its chapter")

    lines = [
        "# Appendix G: Solutions {#app-solutions}",
        "",
        "<!-- GENERATED by tools/gen_solutions.py. Do not edit. -->",
        "",
        f"{len(rows)} of the book's {total} exercises have a worked solution. Each is a program in "
        "the companion examples, beside the chapter's listings, under `examples/chNN/solutions/`, "
        "with its expected output in a `.out` file next to it. The solutions are not printed "
        "here: the listing harness compiles and runs every one of them on every target, exactly "
        "as it does the chapters' listings, so the files are the version that is known to work.",
        "",
        "A solution is one way to do the exercise, not the only one. Several build on a chapter's "
        "own listings or modules and import them, and run from their `solutions/` directory. "
        "A solution marked *blocked* depends on a compiler fix that the toolchain this book is checked "
        "against does not have yet; its `.out` file is the result it gives once the fix is in.",
        "",
        "| Exercise | Chapter | Task | Solution |",
        "|---|---|---|---|",
    ]
    for chap, num, title, task, rel, note in rows:
        task = task.replace("|", "\\|")
        lines.append(f"| {chap}.{num} | {title} | {task} | `{rel}`{note} |")
    lines += [
        "",
        f"<!-- {len(rows)} solutions of {total} exercises, generated "
        f"{datetime.date.today().isoformat()} -->",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"gen_solutions: wrote {out} ({len(rows)} solutions, {total} exercises)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
