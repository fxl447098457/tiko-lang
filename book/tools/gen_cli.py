#!/usr/bin/env python3
"""Generate appendices/C-cli.md from tiko's option table.

src/driver/options.ti holds one OPT( ) row per option, and that one table drives both
the command-line parser and `tiko --help`. The appendix is generated from it so the book
cannot document an option the compiler does not have, or miss one it does.

    python tools/gen_cli.py [--tiko-src C:/dev/tiko-lang]

Where a row's help text is known to be stale in the pinned compiler, NOTES below adds a
correction. Each entry says what was measured -- it is never a guess, and it is removed
once the compiler's own text is fixed.
"""
from __future__ import annotations

import argparse
import datetime
import pathlib
import re
import sys

import pin as pinlib

OPT_RE = re.compile(
    r'OPT\(\s*OPT_\w+,\s*"([^"]+)"\s*,\s*OPTK_(\w+)\s*,\s*OPTCAT_(\w+)\s*,\s*"([^"]*)"\s*,\s*"((?:[^"]|"")*)"\s*\)'
)

CATEGORY_TITLE = {
    "GENERAL": "General",
    "INPUT": "Input",
    "OUTPUT": "Output",
    "TARGET": "Target",
    "DIAG": "Diagnostics",
    "CIMPORT": "C header import (`#cinclude` and `-cimport`)",
    "DEVEL": "Developer and compiler introspection",
}
CATEGORY_ORDER = ["GENERAL", "INPUT", "OUTPUT", "TARGET", "DIAG", "CIMPORT", "DEVEL"]

KIND_FORM = {
    "FLAG": "",
    "VALUE": " ‹{arg}›",
    "JOINED": "‹{arg}›",
    "OPTVALUE": "[=‹{arg}›]",
}

NOTES: dict[str, str] = {}

PREAMBLE = """Environment variables

| Variable | What it does |
|---|---|
| `TIKO_CLANG` | Full path to `clang`. Without it tiko looks at `C:\\Program Files\\LLVM\\bin\\clang.exe` on Windows, `/usr/bin/clang` on Linux or Homebrew's `/opt/homebrew/opt/llvm/bin/clang` on macOS, and searches `PATH` only when that file is absent. `llvm-ar` and `llvm-rc` are taken from the same directory. |
| `TIKO_INCLUDE` | Replaces the default include directory (`<exe>/inc`). `-i` paths are searched first either way. |
| `TIKO_LIBPATH` | Replaces the bundled library directory (`<exe>/lib/<target>`). `-p` paths and `#libpath` are searched first either way. |

Exit codes

| Code | Meaning |
|---|---|
| 0 | success |
| 1 | errors in the program |
| 2 | command-line error |
| 3 | no usable toolchain (clang not found) |
| 4 | internal compiler error |
| 5 | clang or the linker failed |

How arguments are parsed

- An option matches exactly (`-g`), as `--option=value`, or with the value attached (`-O2`, `-Wno-TKO0201`).
- An optional value must be attached with `=`: `--dump-tokens=pp`.
- `--` ends option parsing; everything after it is an input file.
- Inputs are classified by extension: `.o` is an object, `.rc` is a resource script, anything else is source.
- A `#cmdline "..."` line in the first source file restarts the compile with those options, and the source wins over the command line.
"""


# '  tiko build    build the targets of tiko.toml ...' in HelpText's Subcommands block.
SUB_RE = re.compile(r'outp \+= "  tiko (\w+)\s+([^"]+)" & chr')


def main() -> int:
    here = pathlib.Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser()
    pinlib.add_arguments(ap)
    ap.add_argument("--out", default=str(here / "src" / "appendix-C-cli.md"))
    args = ap.parse_args()

    pin = pinlib.read_pin(args.tiko_src, args.rev, args.worktree)
    pinlib.announce(pin, "gen_cli")
    rows = OPT_RE.findall(pinlib.read_source(pin, "src/driver/options.ti"))
    if len(rows) < 20:
        sys.exit(f"gen_cli: only {len(rows)} rows parsed at {pin.commit} -- the table's shape changed")

    lines = [
        "# Appendix C: Command-line reference {#app-cli}",
        "",
        "<!-- GENERATED by tools/gen_cli.py. Do not edit. -->",
        "",
        f"All {len(rows)} options of the pinned compiler, from the table that also drives "
        "`tiko --help`.",
        "",
        PREAMBLE,
        "",
    ]

    # THE SUBCOMMANDS -- tiko build, run, check, clean, metadata -- are words, not options,
    # so they are not in the table; they are read from the --help text that lists them.
    subs = SUB_RE.findall(pinlib.read_source(pin, "src/driver/cmdline.tiko"))
    if subs:
        lines += [
            "## Subcommands {#app-cli-subcommands}",
            "",
            "A subcommand is the first word on the command line. It builds a project from its "
            "`tiko.toml`, as Chapter 31 shows; every other command line is the compiler driver "
            "described by the rest of this appendix.",
            "",
            "| Command | What it does |",
            "|---|---|",
        ]
        for word, text in subs:
            lines.append(f"| `tiko {word}` | {text.replace('|', chr(92) + '|')} |")
        lines.append("")

    # A category the compiler grew and this script does not know about must never be
    # dropped silently: a whole option family went missing that way once.
    unknown = sorted({r[2] for r in rows} - set(CATEGORY_ORDER))
    if unknown:
        sys.exit(
            "gen_cli: unknown option categories "
            + ", ".join(unknown)
            + " -- add them to CATEGORY_ORDER/CATEGORY_TITLE and place them in a chapter"
        )

    for cat in CATEGORY_ORDER:
        chunk = [r for r in rows if r[2] == cat]
        if not chunk:
            continue
        lines += [
            f"## {CATEGORY_TITLE.get(cat, cat.title())} {{#app-cli-{cat.lower()}}}",
            "",
            "| Option | What it does |",
            "|---|---|",
        ]
        for spell, kind, _cat, arg, help_text in chunk:
            form = spell + KIND_FORM.get(kind, "").format(arg=arg or "value")
            text = help_text.replace('""', '"').replace("|", "\\|")
            if spell in NOTES:
                text += f" **Note:** {NOTES[spell]}"
            lines.append(f"| `{form}` | {text} |")
        lines.append("")

    lines += [
        f"<!-- {len(rows)} options, generated {datetime.date.today().isoformat()} from "
        f"src/driver/options.ti at {pin.commit} -->",
        "",
    ]

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"gen_cli: wrote {out} ({len(rows)} options)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
